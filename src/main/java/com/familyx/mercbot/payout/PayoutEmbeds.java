import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Optional;

/** The per-faction embeds in the payouts channel (scope doc 6.6), and the lists they share. */
@Component
public class PayoutEmbeds {

    static final DateTimeFormatter WHEN = DateTimeFormatter.ofPattern("EEE d MMM HH:mm", Locale.UK)
            .withZone(ZoneOffset.UTC);
    static final DateTimeFormatter TIME = DateTimeFormatter.ofPattern("HH:mm").withZone(ZoneOffset.UTC);
    private static final int MAX_LINES = 15;

    private final PayoutRepository repo;
    private final FamilyFactionRepository factions;
    private final BotSettings settings;

    public PayoutEmbeds(PayoutRepository repo, FamilyFactionRepository factions, BotSettings settings) {
        this.repo = repo;
        this.factions = factions;
        this.settings = settings;
    }

    public record Look(MessageEmbed embed, List<ActionRow> rows) { }

    public Look embed(FamilyFaction f) {
        long pool = settings.paymentFactionId();
        boolean isPool = f.tornFactionId() == pool;
        long id = f.tornFactionId();
        Optional<Payout> open = repo.openPayout(id);
        List<Line> ready = repo.ready(id, pool);
        long readyTotal = ready.stream().mapToLong(Line::amount).sum();
        List<Settlement> mine = isPool ? List.of() : repo.inProgress(id);
        Optional<Settlement> sent = mine.stream().filter(s -> "SENT".equals(s.status())).findFirst();

        EmbedBuilder eb = new EmbedBuilder().setColor(Panels.BRAND).setAuthor(f.name().toUpperCase() + " PAYOUTS");
        if (open.isPresent()) {
            List<Line> lines = repo.lines(open.get().id());
            long done = lines.stream().filter(l -> l.creditedAt() != null).count();
            eb.setTitle("💰  Payout #" + open.get().id() + " · " + done + " of " + lines.size() + " credited");
            StringBuilder d = new StringBuilder(table(lines, true));
            d.append("-# Generated by <@").append(open.get().createdBy()).append("> at ")
                    .append(TIME.format(open.get().createdAt())).append(" UTC");
            if (readyTotal > 0) {
                d.append(" · ").append(Money.full(readyTotal)).append(" more owed since, for the next string");
            }
            eb.setDescription(d.toString());
        } else if (readyTotal > 0) {
            eb.setTitle("💰  " + Money.full(readyTotal) + " owed to " + ready.size() + (ready.size() == 1 ? " merc" : " mercs"));
            eb.setDescription((isPool
                    ? "Paid into **" + settings.poolAccountName() + " [" + settings.poolAccountId() + "]** and ready to credit."
                    : "Received from Capacity X and ready to credit in your faction balances.") + "\n" + table(ready, false));
        } else if (sent.isPresent()) {
            eb.setTitle("📨  " + Money.full(sent.get().total()) + " sent by Capacity X");
            eb.setDescription("Press **Mark received** once it reaches " + f.name() + ".");
        } else if (!mine.isEmpty()) {
            long owed = mine.stream().mapToLong(Settlement::total).sum();
            eb.setTitle("🤝  Capacity X owes " + Money.full(owed));
            eb.setDescription("Capacity X's leaders will send it. You'll get a ping when they do.");
        } else {
            eb.setTitle("💰  Nothing owed right now");
            eb.setDescription("Merc shares for " + f.name() + " show here once requesters pay.");
        }

        eb.addField("⏳  Pending", Money.full(repo.pending(id, pool)) + "\n-# invoices not paid yet" + Panels.GAP, true);
        eb.addField("✅  Credited", Money.full(repo.credited7d(id, pool)) + "\n-# last 7 days" + Panels.GAP, true);
        if (isPool) {
            eb.addField("🏦  Faction cut", Money.full(repo.cut7d()) + "\n-# kept in " + settings.poolAccountName()
                    + ", 7 days" + Panels.GAP, true);
            eb.addField("🤝  Settlements", fit(settlements(pool)), false);
        } else {
            long building = repo.unsettled(id);
            String mode = settings.settlementPeriod();
            eb.addField("📥  This period", Money.full(building) + "\n-# " + (Periods.PER_CONTRACT.equals(mode)
                    ? "settled per contract" : "settled at the close") + Panels.GAP, true);
            if (mine.size() > 1 || (open.isPresent() || readyTotal > 0) && !mine.isEmpty()) {
                eb.addField("🤝  From Capacity X", fit(settlementList(mine, false)), false);
            }
        }

        List<ActionRow> rows = new ArrayList<>();
        if (!isPool && sent.isPresent()) {
            rows.add(ActionRow.of(Button.success(CustomId.of("payout", "recv", sent.get().id()),
                    "Mark " + Money.full(sent.get().total()) + " received").withEmoji(Emoji.fromUnicode("📥"))));
        }
        Button gen = Button.primary(CustomId.of("payout", "gen", id),
                open.isPresent() ? "Show payout string" : "Generate payout string").withEmoji(Emoji.fromUnicode("📋"));
        Button credit = Button.secondary(CustomId.of("payout", "credit", id), "Mark credited…")
                .withEmoji(Emoji.fromUnicode("✏️"));
        rows.add(ActionRow.of(open.isEmpty() && readyTotal == 0 ? gen.asDisabled() : gen,
                open.isEmpty() ? credit.asDisabled() : credit));
        if (isPool) {
            List<Settlement> all = repo.inProgress(null);
            if (!all.isEmpty()) {
                StringSelectMenu.Builder pick = StringSelectMenu.create(CustomId.of("payout", "settle"))
                        .setPlaceholder("Settle with a faction…");
                for (Settlement s : all.subList(0, Math.min(25, all.size()))) {
                    pick.addOption(trim(name(s.factionId()) + " · " + Money.full(s.total()), 100), Long.toString(s.id()),
                            trim(period(s) + " · " + ("SENT".equals(s.status()) ? "sent, waiting for them" : "owed"), 100),
                            Emoji.fromUnicode("SENT".equals(s.status()) ? "📨" : "🤝"));
                }
                rows.add(ActionRow.of(pick.build()));
            }
        }
        return new Look(eb.build(), rows);
    }

    /** Capacity X's view of every other faction: settlements in progress, then what's building up. */
    private String settlements(long pool) {
        List<FamilyFaction> others = factions.findActive().stream().filter(f -> f.tornFactionId() != pool).toList();
        if (others.isEmpty()) {
            return "No other family factions." + Panels.GAP;
        }
        List<Settlement> all = repo.inProgress(null);
        StringBuilder sb = new StringBuilder("```\n");
        int width = others.stream().mapToInt(f -> f.name().length()).max().orElse(8);
        for (FamilyFaction f : others) {
            List<Settlement> fs = all.stream().filter(s -> s.factionId() == f.tornFactionId()).toList();
            long building = repo.unsettled(f.tornFactionId());
            if (fs.isEmpty() && building == 0) {
                sb.append(pad(f.name(), width)).append("   nothing to settle\n");
                continue;
            }
            for (Settlement s : fs) {
                sb.append(pad(f.name(), width)).append("   ").append(padLeft(Money.full(s.total()), 12)).append("   ")
                        .append("SENT".equals(s.status()) ? "Sent " + WHEN.format(s.sentAt()) + " · waiting" : "Owed")
                        .append(" · ").append(period(s)).append('\n');
            }
            if (building > 0) {
                sb.append(pad(f.name(), width)).append("   ").append(padLeft(Money.full(building), 12))
                        .append("   this period so far\n");
            }
        }
        sb.append("```");
        Instant next = Periods.nextClose(settings.settlementPeriod(), Instant.now());
        sb.append(next == null ? "-# Settled as each invoice is paid in full."
                : "-# This period closes " + WHEN.format(next) + " UTC.");
        return sb + Panels.GAP;
    }

    private String settlementList(List<Settlement> list, boolean withFaction) {
        StringBuilder sb = new StringBuilder();
        for (Settlement s : list) {
            sb.append("SENT".equals(s.status()) ? "📨 " : "🤝 ").append(withFaction ? name(s.factionId()) + " · " : "")
                    .append("**").append(Money.full(s.total())).append("** · ").append(period(s)).append(" · ")
                    .append("SENT".equals(s.status()) ? "sent " + WHEN.format(s.sentAt()) + " UTC" : "owed").append('\n');
        }
        return sb + Panels.GAP;
    }

    /** "week 2–8 Nov", "October 2026", or the contract reference for per-contract settlement. */
    public String period(Settlement s) {
        if (s.contractId() != null) {
            return repo.contractRef(s.contractId()).orElse("contract");
        }
        return Periods.label(s.periodStart(), s.periodEnd());
    }

    public String name(long factionId) {
        return factions.find(factionId).map(FamilyFaction::name).orElse("Faction " + factionId);
    }

    /** A code-block table of mercs and amounts; with status, credited lines show their time. */
    static String table(List<Line> lines, boolean status) {
        if (lines.isEmpty()) {
            return "";
        }
        int width = lines.stream().limit(MAX_LINES).mapToInt(l -> who(l).length()).max().orElse(10);
        StringBuilder sb = new StringBuilder("```\n");
        lines.stream().limit(MAX_LINES).forEach(l -> {
            sb.append(pad(who(l), width)).append("   ").append(padLeft(Money.full(l.amount()), 12));
            if (status) {
                sb.append("   ").append(l.creditedAt() == null ? "waiting" : "✅ credited " + TIME.format(l.creditedAt()));
            }
            sb.append('\n');
        });
        if (lines.size() > MAX_LINES) {
            sb.append("+").append(lines.size() - MAX_LINES).append(" more\n");
        }
        return sb.append("```").toString();
    }

    public static String who(Line l) {
        return (l.name() == null ? "Player" : l.name()) + " [" + l.mercId() + "]";
    }

    private static String pad(String s, int w) {
        return s.length() >= w ? s : s + " ".repeat(w - s.length());
    }

    private static String padLeft(String s, int w) {
        return s.length() >= w ? s : " ".repeat(w - s.length()) + s;
    }

    /** Embed fields hold at most 1024 characters; keeps a code block closed if it has to cut. */
    private static String fit(String s) {
        if (s.length() <= 1024) {
            return s;
        }
        String cut = s.substring(0, 1000);
        return cut + (cut.split("```", -1).length % 2 == 0 ? "\n…```" : "\n…");
    }

    static String trim(String s, int max) {
        return s.length() <= max ? s : s.substring(0, max - 1) + "…";
    }
}
